import Foundation
import PackagePlugin

/// Build-tool plugin of the PrismProtocol target: generates
/// `PrismVersion.swift`, which defines `PrismInfo.version` from the `VERSION`
/// file at the package root and `PrismInfo.build` from the
/// `PRISM_BUILD_NUMBER` environment variable (default `1`).
///
/// It is a prebuild command, so it runs on every build and picks up a new
/// build number even when no file changed. The file is rewritten only when
/// its content changes, so an unchanged version recompiles nothing.
@main
struct VersionPlugin: BuildToolPlugin {
    func createBuildCommands(context: PluginContext, target: Target) async throws -> [Command] {
        let versionFile = context.package.directoryURL.appending(path: "VERSION")
        let raw: String
        do {
            raw = try String(contentsOf: versionFile, encoding: .utf8)
        } catch {
            throw VersionError("cannot read \(versionFile.path): \(error.localizedDescription)")
        }
        let version = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard Self.isSemver(version) else {
            throw VersionError("VERSION holds '\(version)', which is not a SemVer version (e.g. 1.0.0 or 1.1.0-rc1)")
        }
        let build = ProcessInfo.processInfo.environment["PRISM_BUILD_NUMBER"].flatMap { $0.isEmpty ? nil : $0 } ?? "1"
        guard build.wholeMatch(of: /[0-9]+(\.[0-9]+)*/) != nil else {
            throw VersionError("PRISM_BUILD_NUMBER is '\(build)'; it must be numeric, e.g. 42 or 1.2")
        }

        let source = """
            // Generated by Plugins/VersionPlugin from VERSION and PRISM_BUILD_NUMBER. Do not edit.

            extension PrismInfo {
                /// The semantic version, from the `VERSION` file.
                public static let version = "\(version)"
                /// The build number (`CFBundleVersion`), from `PRISM_BUILD_NUMBER`.
                public static let build = "\(build)"
            }

            """
        let outputDir = context.pluginWorkDirectoryURL.appending(path: "Generated")
        // Writes the file only when its content changes (keeps the mtime, so
        // nothing recompiles); the temporary copy lives outside outputDir.
        let script = #"""
            set -eu
            mkdir -p "$2"
            printf '%s' "$1" > "$3"
            if cmp -s "$3" "$2/PrismVersion.swift"; then rm -f "$3"; else mv "$3" "$2/PrismVersion.swift"; fi
            """#
        return [
            .prebuildCommand(
                displayName: "Generating PrismVersion.swift (\(version), build \(build))",
                executable: URL(filePath: "/bin/sh"),
                arguments: ["-c", script, "sh", source, outputDir.path,
                            context.pluginWorkDirectoryURL.appending(path: "PrismVersion.swift.tmp").path],
                outputFilesDirectory: outputDir
            ),
        ]
    }

    /// SemVer 2.0, the grammar of `PrismInfo.isSemver` and scripts/lib/semver.sh.
    static func isSemver(_ text: String) -> Bool {
        text.wholeMatch(of: /(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-[0-9A-Za-z-]+(\.[0-9A-Za-z-]+)*)?(\+[0-9A-Za-z-]+(\.[0-9A-Za-z-]+)*)?/) != nil
    }
}

struct VersionError: Error, CustomStringConvertible {
    let description: String
    init(_ description: String) { self.description = description }
}
